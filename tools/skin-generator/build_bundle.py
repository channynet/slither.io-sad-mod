"""Rebuild the embedded script from the retained color laboratory sources."""
from pathlib import Path
import hashlib
import os
import subprocess

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'build/skin-generator.js'
OUTPUT.parent.mkdir(exist_ok=True)
subprocess.run(['npx.cmd' if os.name == 'nt' else 'npx', '--yes', 'esbuild@0.27.3',
                str(Path(__file__).with_name('random.ts')), '--bundle', '--minify',
                '--format=iife', '--platform=neutral', '--target=es2020', '--charset=utf8',
                '--outfile=' + str(OUTPUT)], check=True, cwd=ROOT)
data = OUTPUT.read_bytes()
header = '// Generated by tools/skin-generator/build_bundle.py. Do not edit.\n'
header += '// Script SHA-256: ' + hashlib.sha256(data).hexdigest() + '\n'
header += 'static const unsigned char skin_generator_bundle[] = {\n'
data += b'\0'
header += '\n'.join('  ' + ','.join(f'0x{b:02x}' for b in data[i:i+24]) + ',' for i in range(0,len(data),24))
header += '\n};\n'
(ROOT/'app/src/game/skin_generator_bundle.h').write_text(header,encoding='utf-8')
print('Embedded generator:',len(data)-1,'bytes')
